#!/usr/bin/env python3
"""Generate core/uninstall.sh from the modules and builder/retired_modules.json.

    python builder/generate_uninstall.py            write core/uninstall.sh
    python builder/generate_uninstall.py --check    exit 1 if it is out of date

What it removes, and from where it learns it:
- GEM screens: every modules/*/engdefs/*.esd by its exact name, plus any
  module.json "uninstall": {"engdefs": [...]} and the retired list's patterns.
- Script folders under /mnt/efs-system/scripts: the script_dir of every module
  that installs to flash, plus "uninstall": {"script_dirs": [...]} and the
  retired list's folders.
- What it does not undo (boot images, manage_cd.sh, network files, payloads
  outside engdefs/scripts): each module's "uninstall": {"note": "..."} is
  printed, so the user knows which card or script reverts it.

A module that manages its own removal (wifi-sta) gives only a note, and its
files are left alone: removing part of it would leave the rest running.
tests/test_uninstall_coverage.py checks that core/uninstall.sh is up to date
and covers every GEM screen and script folder.
"""
import argparse
import glob
import json
import os
import sys

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MODULES_DIR = os.path.join(REPO_ROOT, 'modules')
RETIRED = os.path.join(REPO_ROOT, 'builder', 'retired_modules.json')
OUT_FILE = os.path.join(REPO_ROOT, 'core', 'uninstall.sh')


def collect(modules_dir=MODULES_DIR, retired_path=RETIRED):
    """(engdefs, script_dirs, notes): sorted lists; notes as (module, text)."""
    engdefs, dirs, notes = set(), set(), []
    for meta_file in sorted(glob.glob(os.path.join(modules_dir, '*', 'module.json'))):
        mod_dir = os.path.dirname(meta_file)
        with open(meta_file, encoding='utf-8') as f:
            meta = json.load(f)
        name = meta.get('name', os.path.basename(mod_dir))
        un = meta.get('uninstall', {})
        if isinstance(un, str):          # older modules give a plain note
            un = {'note': un}
        if not un.get('own_removal'):
            for esd in glob.glob(os.path.join(mod_dir, 'engdefs', '*.esd')):
                engdefs.add(os.path.basename(esd))
            engdefs.update(un.get('engdefs', []))
            if meta.get('installs_to_flash', True):
                dirs.add(meta.get('script_dir', f'/scripts/{name}').strip('/').split('/', 1)[-1])
            dirs.update(un.get('script_dirs', []))
        if un.get('note'):
            notes.append((name, un['note']))
    with open(retired_path, encoding='utf-8') as f:
        retired = json.load(f)['retired']
    for entry in retired:
        engdefs.update(entry.get('engdefs', []))
        dirs.update(entry.get('script_dirs', []))
        if entry.get('note_for_user'):
            notes.append((entry['name'], entry['note_for_user']))
    return sorted(engdefs), sorted(dirs), notes


def render(engdefs, dirs, notes):
    q = lambda s: s.replace('\\', '\\\\').replace('"', '\\"').replace('$', '\\$').replace('`', '\\`')
    lines = [
        '#!/bin/ksh',
        '# MMI3G-Toolkit Uninstaller',
        '# GENERATED by builder/generate_uninstall.py from modules/*/module.json and',
        '# builder/retired_modules.json. Do not edit by hand: change those and re-run it.',
        '# Removes the GEM screens and script folders any toolkit version installed.',
        '# Safe to run even if only some modules were installed: missing items are skipped.',
        '',
        'EFSDIR="/mnt/efs-system"',
        'ENGDEFS="${EFSDIR}/engdefs"',
        'SCRIPTS="${EFSDIR}/scripts"',
        '',
        'echo "============================================"',
        'echo " MMI3G-Toolkit Uninstaller"',
        'echo " $(date)"',
        'echo "============================================"',
        'echo ""',
        '',
        'if [ ! -d "${EFSDIR}" ]; then',
        '    echo "[ERROR] ${EFSDIR} not found. Not running on MMI?"',
        '    exit 1',
        'fi',
        '',
        'mount -uw ${EFSDIR}',
        'if [ $? -ne 0 ]; then',
        '    echo "[ERROR] Failed to remount ${EFSDIR} read-write"',
        '    exit 1',
        'fi',
        'echo "[OK] ${EFSDIR} remounted rw"',
        'echo ""',
        '',
        '# GEM screens (.esd files in /mnt/efs-system/engdefs): current modules by',
        '# name, earlier versions by pattern.',
        'echo "--- Removing GEM screens ---"',
        'REMOVED_ESD=0',
        'for pattern in \\',
    ]
    lines += [f'    "{e}" \\' for e in engdefs[:-1]] + [f'    "{engdefs[-1]}"']
    lines += [
        'do',
        '    for f in ${ENGDEFS}/${pattern}; do',
        '        if [ -f "${f}" ]; then',
        '            rm -v "${f}"',
        '            REMOVED_ESD=$((REMOVED_ESD + 1))',
        '        fi',
        '    done',
        'done',
        'echo "  ${REMOVED_ESD} GEM screen(s) removed"',
        'echo ""',
        '',
        '# Script folders under /mnt/efs-system/scripts (module.json script_dir, and',
        '# earlier versions\' folders).',
        'echo "--- Removing script folders ---"',
        'REMOVED_DIRS=0',
        'for d in \\',
    ]
    lines += [f'    {d} \\' for d in dirs[:-1]] + [f'    {dirs[-1]}']
    lines += [
        'do',
        '    if [ -d "${SCRIPTS}/${d}" ]; then',
        '        rm -rf "${SCRIPTS}/${d}"',
        '        echo "  Removed ${SCRIPTS}/${d}"',
        '        REMOVED_DIRS=$((REMOVED_DIRS + 1))',
        '    fi',
        'done',
        'echo "  ${REMOVED_DIRS} script folder(s) removed"',
        'echo ""',
        '',
        '# Changes outside engdefs/scripts are not undone here: each needs its own',
        '# backup or card.',
        'echo "--- Not undone here (each has its own way back) ---"',
    ]
    lines += [f'echo "  {q(name)}: {q(text)}"' for name, text in notes]
    lines += [
        'echo ""',
        '',
        'sync',
        'mount -ur ${EFSDIR} 2>/dev/null',
        '',
        'echo "============================================"',
        'echo " Uninstall complete."',
        'echo " Reboot MMI: hold MENU + knob + upper-right soft key"',
        'echo "============================================"',
    ]
    return '\n'.join(lines) + '\n'


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--check', action='store_true', help='exit 1 if core/uninstall.sh is out of date')
    args = ap.parse_args(argv)
    text = render(*collect())
    if args.check:
        with open(OUT_FILE, encoding='utf-8', newline='') as f:
            current = f.read().replace('\r\n', '\n')
        if current != text:
            print('core/uninstall.sh is out of date: run python builder/generate_uninstall.py')
            return 1
        print('core/uninstall.sh is up to date')
        return 0
    with open(OUT_FILE, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    print(f'wrote {OUT_FILE}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
